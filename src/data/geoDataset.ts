// Helper functions to query dataset easily
export function getAllCountries(): Country[] {
  return CONTINENTS_DATA.flatMap((c) => c.countries);
}

export function getAllCities(): Array<{ city: (typeof CONTINENTS_DATA)[0]['countries'][0]['cities'][0]; country: Country }> {
  return getAllCountries().flatMap((country) =>
    country.cities.map((city) => ({ city, country }))
  );
}

export function getCountryById(id: string): Country | undefined {
  return getAllCountries().find((c) => c.id === id);
}

export function getContinentById(id: string): Continent | undefined {
  return CONTINENTS_DATA.find((c) => c.id === id);
}
